import '../../domain/entities/user.dart';

class UserModel extends UserEntity {
  const UserModel({
    required super.id,
    super.authUserId,
    required super.email,
    required super.firstName,
    required super.lastName,
    required super.phone,
    required super.role,
    super.companyId,
    super.deliveryAgentId,
    super.deliveryAgentCode,
    super.distributionCenterName,
    super.lifetimeDeliveriesCount,
    super.rating,
    super.personnelType,
    super.compensationType,
    super.commissionRate,
    super.transportAllowance,
    super.fuelAllowance,
    super.baseSalary,
    super.vehicleType,
    super.vehiclePlateNumber,
    super.operatingState,
    super.operatingCity,
    super.bankName,
    super.bankAccountNumber,
    super.bankAccountName,
    super.agentStatus,
    super.avatarUrl,
  });

  factory UserModel.fromJson(Map<String, dynamic> json, {String? deliveryAgentId}) {
    return UserModel(
      id: json['id'] ?? '',
      authUserId: json['auth_user_id'],
      email: json['email'] ?? '',
      firstName: json['first_name'] ?? '',
      lastName: json['last_name'] ?? '',
      phone: json['phone'] ?? json['phone_number'] ?? '',
      role: json['role'] ?? 'delivery_agent',
      companyId: json['company_id'],
      deliveryAgentId: deliveryAgentId,
      deliveryAgentCode: json['delivery_agent_code'] ?? json['agent_code'] ?? '',
      distributionCenterName: json['distribution_center_name'] ?? json['dc_name'] ?? '',
      lifetimeDeliveriesCount: (json['lifetime_deliveries_count'] as num?)?.toInt() ?? 0,
      rating: (json['rating'] as num?)?.toDouble() ?? 0.0,
      personnelType: json['personnel_type'] ?? 'pda',
      compensationType: json['compensation_type'] ?? 'commission',
      commissionRate: (json['commission_rate'] as num?)?.toDouble() ?? 0.0,
      transportAllowance: (json['transport_allowance'] as num?)?.toDouble() ?? 0.0,
      fuelAllowance: (json['fuel_allowance'] as num?)?.toDouble() ?? 0.0,
      baseSalary: (json['base_salary'] as num?)?.toDouble() ?? 0.0,
      vehicleType: json['vehicle_type'] ?? '',
      vehiclePlateNumber: json['vehicle_plate_number'] ?? '',
      operatingState: json['operating_state'] ?? '',
      operatingCity: json['operating_city'] ?? '',
      bankName: json['bank_name'] ?? '',
      bankAccountNumber: json['bank_account_number'] ?? '',
      bankAccountName: json['bank_account_name'] ?? '',
      agentStatus: json['current_status'] ?? 'available',
      avatarUrl: json['avatar_url']?.toString(),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'auth_user_id': authUserId,
      'email': email,
      'first_name': firstName,
      'last_name': lastName,
      'phone': phone,
      'role': role,
      'company_id': companyId,
      'delivery_agent_code': deliveryAgentCode,
      'distribution_center_name': distributionCenterName,
      'lifetime_deliveries_count': lifetimeDeliveriesCount,
      'rating': rating,
      'personnel_type': personnelType,
      'compensation_type': compensationType,
      'commission_rate': commissionRate,
      'transport_allowance': transportAllowance,
      'fuel_allowance': fuelAllowance,
      'base_salary': baseSalary,
      'vehicle_type': vehicleType,
      'vehicle_plate_number': vehiclePlateNumber,
      'operating_state': operatingState,
      'operating_city': operatingCity,
      'bank_name': bankName,
      'bank_account_number': bankAccountNumber,
      'bank_account_name': bankAccountName,
      'current_status': agentStatus,
      'avatar_url': avatarUrl,
    };
  }
}
