import 'dart:convert';
import 'package:flutter/services.dart';

class StateLgaData {
  final String state;
  final String alias;
  final List<String> lgas;

  const StateLgaData({
    required this.state,
    required this.alias,
    required this.lgas,
  });

  factory StateLgaData.fromJson(Map<String, dynamic> json) {
    return StateLgaData(
      state: json['state']?.toString() ?? '',
      alias: json['alias']?.toString() ?? '',
      lgas: (json['lgas'] as List<dynamic>?)
              ?.map((e) => e.toString().trim())
              .where((e) => e.isNotEmpty)
              .toList() ??
          [],
    );
  }
}

