      }
    }
    return rawState.trim();
  }

  /// Returns all LGAs for a given state
  static List<String> getLgasForState(String rawState) {
    final normalized = normalizeStateName(rawState);
    if (_stateLgaCache.containsKey(normalized)) {
      return _stateLgaCache[normalized]!;
    }
    if (_defaultStaticStateLgas.containsKey(normalized)) {
      return _defaultStaticStateLgas[normalized]!;
    }

    // Case-insensitive fallback search
    for (final entry in _defaultStaticStateLgas.entries) {
      if (entry.key.toLowerCase() == normalized.toLowerCase() ||
          normalized.toLowerCase().contains(entry.key.toLowerCase())) {
        return entry.value;
      }
    }

    return const [];
  }

  /// Checks if an LGA belongs to a State
  static bool isLgaInState(String rawState, String rawLga) {
    final lgas = getLgasForState(rawState);
    final target = rawLga.trim().toLowerCase();
    return lgas.any((l) => l.toLowerCase() == target || target.contains(l.toLowerCase()) || l.toLowerCase().contains(target));
  }
