  /// Initializes the service by reading `assets/nigeria-state-and-lgas.json`
  static Future<void> initialize() async {
    if (_isLoaded && _stateLgaCache.isNotEmpty) return;

    try {
      final jsonString = await rootBundle.loadString('assets/nigeria-state-and-lgas.json');
      final dynamic decoded = jsonDecode(jsonString);

      if (decoded is List) {
        final map = <String, List<String>>{};
        for (final item in decoded) {
          if (item is Map<String, dynamic>) {
            final stateObj = StateLgaData.fromJson(item);
            if (stateObj.state.isNotEmpty) {
              map[stateObj.state] = stateObj.lgas;
            }
          }
        }
        if (map.isNotEmpty) {
          _stateLgaCache = map;
          _cachedStates = map.keys.toList()..sort();
          _isLoaded = true;
          return;
        }
      }
    } catch (_) {
      // Fallback to embedded complete dataset
    }

    _stateLgaCache = Map.from(_defaultStaticStateLgas);
    _cachedStates = _stateLgaCache.keys.toList()..sort();
    _isLoaded = true;
  }

  /// Returns all 36 Nigerian States + FCT in sorted order
  static List<String> getAllStates() {
    if (!_isLoaded || _cachedStates.isEmpty) {
      _cachedStates = _defaultStaticStateLgas.keys.toList()..sort();
    }
    return _cachedStates;
  }

  /// Normalizes state names (handles "Abuja FCT", "FCT", "Lagos State", etc.)
  static String normalizeStateName(String rawState) {
    final clean = rawState.trim().toLowerCase();
    if (clean.isEmpty) return 'Federal Capital Territory';

    if (clean.contains('abuja') || clean.contains('fct') || clean.contains('capital')) {
      return 'Federal Capital Territory';
    }
    if (clean.contains('lagos')) return 'Lagos';
    if (clean.contains('rivers') || clean.contains('port harcourt')) return 'Rivers';
    if (clean.contains('kano')) return 'Kano';
    if (clean.contains('kaduna')) return 'Kaduna';
    if (clean.contains('oyo') || clean.contains('ibadan')) return 'Oyo';
    if (clean.contains('enugu')) return 'Enugu';
    if (clean.contains('delta')) return 'Delta';
    if (clean.contains('edo') || clean.contains('benin')) return 'Edo';
    if (clean.contains('ogun')) return 'Ogun';
    if (clean.contains('anambra')) return 'Anambra';
    if (clean.contains('akwa ibom') || clean.contains('uyo')) return 'Akwa Ibom';
    if (clean.contains('plateau') || clean.contains('jos')) return 'Plateau';
    if (clean.contains('cross river') || clean.contains('calabar')) return 'Cross River';
    if (clean.contains('imo') || clean.contains('owerri')) return 'Imo';
    if (clean.contains('abia')) return 'Abia';
